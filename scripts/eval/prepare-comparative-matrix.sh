#!/usr/bin/env bash
# Stage the fixed, fresh-arm comparative matrix. This script intentionally does
# not start fixtures, daemons, or Codex: those lifecycle operations stay with
# the parent executor so readiness, warm preparation, and cleanup are visible
# in one parent transcript.

set -euo pipefail
IFS=$'\n\t'
umask 077

usage() {
    cat <<'EOF'
Usage:
  prepare-comparative-matrix.sh \
    --run-root DIR --codex-bin PATH --wirecmd PATH \
    --memory PATH --everything PATH --conformance PATH \
    --mcpc-runtime DIR [--model ID] [--http-base-port PORT]

Create twelve fresh arm roots for the fixed 3-condition, 2-cold/2-warm
comparative matrix. DIR must not already exist. The supplied fixture binaries
must be the pinned official Go SDK v1.7.0 builds. --mcpc-runtime must contain
node_modules/.bin/mcpc for mcpc v0.6.0 and share a filesystem with DIR; its
files are hard-linked into each read-only arm tools/ directory.

This stages only inputs and an immutable execution plan. It never starts a
daemon, fixture, session, or model. The parent executor must follow
docs/notes/comparative-matrix-scaffold.md before releasing an evaluator.
EOF
}

fail() {
    printf '%s\n' "prepare-comparative-matrix: $*" >&2
    exit 2
}

absolute_file() {
    local path=$1 resolved
    resolved=$(realpath -e -- "$path") || fail "cannot resolve file: $path"
    [[ -f $resolved ]] || fail "not a regular file: $path"
    printf '%s\n' "$resolved"
}

absolute_dir() {
    local path=$1 resolved
    resolved=$(realpath -e -- "$path") || fail "cannot resolve directory: $path"
    [[ -d $resolved ]] || fail "not a directory: $path"
    printf '%s\n' "$resolved"
}

json_string() {
    local value=$1
    value=${value//\\/\\\\}
    value=${value//\"/\\\"}
    value=${value//$'\n'/\\n}
    value=${value//$'\r'/\\r}
    value=${value//$'\t'/\\t}
    printf '"%s"' "$value"
}

kdl_string() {
    json_string "$1"
}

digest_tree() {
    local path=$1
    (
        cd -- "$path"
        find . -type f -print0 | sort -z | xargs -0 -r sha256sum --
        find . -type l -printf 'link %p -> %l\n' | LC_ALL=C sort
    ) | sha256sum | awk '{print $1}'
}

copy_executable() {
    local source=$1 destination=$2
    install -m 0555 -- "$source" "$destination"
}

write_native_wrapper() {
    local target=$1 server=$2
    # The inputs are canonical absolute paths generated by this script. Reject
    # quote/newline-bearing paths rather than emitting shell that a wrapper
    # could parse differently.
    [[ $server != *"'"* && $server != *$'\n'* ]] || fail "fixture path is not wrapper-safe"
    {
        printf '%s\n' '#!/bin/sh'
        printf 'exec /usr/bin/env -i PATH=/usr/bin:/bin '\''%s'\''\n' "$server"
    } >"$target"
    chmod 0555 -- "$target"
}

wirecmd=
memory=
everything=
conformance=
mcpc_runtime=
codex_bin=
run_root=
model=gpt-5.6-luna
http_base_port=39200

while (($#)); do
    case $1 in
        --wirecmd) wirecmd=${2-}; shift 2 ;;
        --memory) memory=${2-}; shift 2 ;;
        --everything) everything=${2-}; shift 2 ;;
        --conformance) conformance=${2-}; shift 2 ;;
        --mcpc-runtime) mcpc_runtime=${2-}; shift 2 ;;
        --codex-bin) codex_bin=${2-}; shift 2 ;;
        --run-root) run_root=${2-}; shift 2 ;;
        --model) model=${2-}; shift 2 ;;
        --http-base-port) http_base_port=${2-}; shift 2 ;;
        --help|-h) usage; exit 0 ;;
        *) fail "unknown argument: $1" ;;
    esac
done

[[ -n $wirecmd && -n $memory && -n $everything && -n $conformance && -n $mcpc_runtime && -n $codex_bin && -n $run_root ]] || {
    usage >&2
    exit 2
}
[[ $model =~ ^gpt-5\.6-(luna|terra|sol)$ ]] || fail "--model must name a GPT-5.6 evaluator model"
if ! [[ $http_base_port =~ ^[0-9]+$ ]] || ((http_base_port < 1024 || http_base_port > 65523)); then
    fail "--http-base-port must leave twelve unprivileged ports"
fi

wirecmd=$(absolute_file "$wirecmd")
memory=$(absolute_file "$memory")
everything=$(absolute_file "$everything")
conformance=$(absolute_file "$conformance")
codex_bin=$(absolute_file "$codex_bin")
mcpc_runtime=$(absolute_dir "$mcpc_runtime")
[[ -x $wirecmd && -x $memory && -x $everything && -x $conformance && -x $codex_bin ]] || fail "all supplied binaries must be executable"
mcpc_entry=$(absolute_file "$mcpc_runtime/node_modules/.bin/mcpc")
[[ -x $mcpc_entry ]] || fail "mcpc entrypoint is not executable: $mcpc_entry"

[[ $run_root != / && $run_root == /* ]] || fail "--run-root must be an absolute non-root path"
[[ ! -e $run_root && ! -L $run_root ]] || fail "refusing to overwrite existing --run-root: $run_root"
run_parent=$(dirname -- "$run_root")
[[ -d $run_parent ]] || fail "--run-root parent does not exist: $run_parent"
[[ $(stat -c %d -- "$run_parent") == $(stat -c %d -- "$mcpc_runtime") ]] || fail "--run-root and --mcpc-runtime must share a filesystem for immutable hard-link staging"

script_dir=$(unset CDPATH; cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
repo_root=$(unset CDPATH; cd -- "$script_dir/../.." && pwd -P)
task_source=$script_dir/comparative-task.txt
skill_source=$repo_root/skills/wirecmd/SKILL.md
[[ -f $task_source && -f $skill_source ]] || fail "required task or Wirecmd Skill source is missing"

mkdir -p -- "$run_root"
trap 'printf "%s\\n" "prepare-comparative-matrix: staging failed; retaining $run_root for inspection" >&2' ERR

task_hash=$(sha256sum -- "$task_source" | awk '{print $1}')
skill_hash=$(sha256sum -- "$skill_source" | awk '{print $1}')
mcpc_tree_hash=$(digest_tree "$mcpc_runtime")
mkdir -p -- "$run_root/parent"

{
    printf 'schema=1\n'
    printf 'model=%q\n' "$model"
    printf 'task_sha256=%s\n' "$task_hash"
    printf 'wirecmd_skill_sha256=%s\n' "$skill_hash"
    printf 'wirecmd_sha256=%s\n' "$(sha256sum -- "$wirecmd" | awk '{print $1}')"
    printf 'memory_sha256=%s\n' "$(sha256sum -- "$memory" | awk '{print $1}')"
    printf 'everything_sha256=%s\n' "$(sha256sum -- "$everything" | awk '{print $1}')"
    printf 'conformance_sha256=%s\n' "$(sha256sum -- "$conformance" | awk '{print $1}')"
    printf 'mcpc_entry_sha256=%s\n' "$(sha256sum -- "$mcpc_entry" | awk '{print $1}')"
    printf 'mcpc_tree_sha256=%s\n' "$mcpc_tree_hash"
    printf 'codex_sha256=%s\n' "$(sha256sum -- "$codex_bin" | awk '{print $1}')"
    printf 'http_base_port=%s\n' "$http_base_port"
} >"$run_root/parent/input-manifest.env"

cat >"$run_root/plan.tsv" <<'EOF'
sequence	run_id	condition	preparation	repetition
1	wirecmd-cold-1	wirecmd	cold	1
2	mcpc-warm-1	mcpc	warm	1
3	native-cold-1	native	cold	1
4	mcpc-cold-1	mcpc	cold	1
5	native-warm-1	native	warm	1
6	wirecmd-warm-1	wirecmd	warm	1
7	native-cold-2	native	cold	2
8	wirecmd-cold-2	wirecmd	cold	2
9	mcpc-warm-2	mcpc	warm	2
10	wirecmd-warm-2	wirecmd	warm	2
11	mcpc-cold-2	mcpc	cold	2
12	native-warm-2	native	warm	2
EOF

stage_arm() {
    local sequence=$1 id=$2 condition=$3 preparation=$4 repetition=$5
    local arm=$run_root/arms/$id port=$((http_base_port + sequence - 1))
    local tools=$arm/tools inputs=$arm/inputs workspace=$arm/workspace runtime=$arm/runtime state=$arm/state parent=$arm/parent
    local fixture_dir=$parent/fixtures native_mcp_dir=$parent/native-mcp
    local wirecmd_config mcpc_config

    mkdir -p -- "$tools" "$inputs" "$workspace" "$runtime" "$state" "$parent/logs" "$fixture_dir"
    copy_executable "$conformance" "$fixture_dir/conformance-server"

    cp -- "$task_source" "$inputs/task.txt"
    case $condition in
        wirecmd)
            copy_executable "$wirecmd" "$tools/wirecmd"
            copy_executable "$memory" "$fixture_dir/memory-server"
            copy_executable "$everything" "$fixture_dir/everything-server"
            wirecmd_config=$inputs/config
            {
                printf 'wirecmd {\n'
                printf '    root %s\n' "$(kdl_string "$workspace")"
                printf '    server "memory" {\n        scope "workspace"\n        stdio %s\n    }\n' "$(kdl_string "$fixture_dir/memory-server")"
                printf '    server "remote-tests" {\n        scope "workspace"\n        http %s\n    }\n' "$(kdl_string "http://127.0.0.1:$port/mcp")"
                printf '    server "everything" {\n        scope "workspace"\n        stdio %s\n    }\n' "$(kdl_string "$fixture_dir/everything-server")"
                printf '}\n'
            } >"$wirecmd_config"
            {
                printf '%s\n\n' 'Use Wirecmd only, in normal daemon-backed mode. Its assigned configuration path is in CAPABILITY_CONFIG; pass that path to Wirecmd without reading the configuration. Do not use --direct.'
                cat -- "$skill_source"
                printf '\n\n'
                cat -- "$task_source"
            } >"$inputs/prompt.txt"
            cp -- "$skill_source" "$inputs/assigned-wirecmd-skill.md"
            ;;
        mcpc)
            copy_executable "$memory" "$tools/memory-server"
            copy_executable "$everything" "$tools/everything-server"
            cp -al -- "$mcpc_runtime" "$tools/mcpc-runtime"
            ln -s mcpc-runtime/node_modules/.bin/mcpc "$tools/mcpc"
            mcpc_config=$inputs/config
            {
                printf '{\n  "mcpServers": {\n'
                printf '    "memory": {"command": %s, "args": []},\n' "$(json_string "$tools/memory-server")"
                printf '    "remote-tests": {"url": %s},\n' "$(json_string "http://127.0.0.1:$port/mcp")"
                printf '    "everything": {"command": %s, "args": []}\n' "$(json_string "$tools/everything-server")"
                printf '  }\n}\n'
            } >"$mcpc_config"
            {
                printf '%s\n\n' 'Use mcpc only. Its assigned configuration path is in CAPABILITY_CONFIG; use it without reading its contents. You may use mcpc normal named sessions in MCPC_HOME_DIR.'
                cat -- "$task_source"
            } >"$inputs/prompt.txt"
            ;;
        native)
            mkdir -p -- "$native_mcp_dir"
            copy_executable "$memory" "$native_mcp_dir/memory-server"
            copy_executable "$everything" "$native_mcp_dir/everything-server"
            write_native_wrapper "$native_mcp_dir/memory-mcp" "$native_mcp_dir/memory-server"
            write_native_wrapper "$native_mcp_dir/everything-mcp" "$native_mcp_dir/everything-server"
            {
                printf '%s\n\n' 'Use only the three native MCP servers registered for this Codex session plus ordinary shell tools. Native MCP calls may not be available inside an ordinary shell program; if so, report that as an interface property rather than task failure.'
                cat -- "$task_source"
            } >"$inputs/prompt.txt"
            ;;
        *) fail "unknown condition: $condition" ;;
    esac

    {
        printf 'sequence=%q\n' "$sequence"
        printf 'run_id=%q\n' "$id"
        printf 'condition=%q\n' "$condition"
        printf 'preparation=%q\n' "$preparation"
        printf 'repetition=%q\n' "$repetition"
        printf 'model=%q\n' "$model"
        printf 'http_port=%q\n' "$port"
        printf 'http_url=%q\n' "http://127.0.0.1:$port/mcp"
        printf 'arm_root=%q\n' "$arm"
        printf 'conformance_binary=%q\n' "$fixture_dir/conformance-server"
        case $condition in
            wirecmd) printf 'capability_config=%q\n' "$wirecmd_config" ;;
            mcpc) printf 'capability_config=%q\n' "$mcpc_config" ;;
            native)
                printf 'native_mcp_root=%q\n' "$native_mcp_dir"
                printf 'native_stdio_memory=%q\n' "memory=$native_mcp_dir/memory-mcp"
                printf 'native_stdio_everything=%q\n' "everything=$native_mcp_dir/everything-mcp"
                printf 'native_http=%q\n' "remote-tests=http://127.0.0.1:$port/mcp"
                ;;
        esac
    } >"$parent/arm.env"

    {
        sha256sum -- "$inputs/task.txt" "$inputs/prompt.txt" "$fixture_dir/conformance-server"
        case $condition in
            wirecmd) sha256sum -- "$inputs/config" "$tools/wirecmd" "$fixture_dir/memory-server" "$fixture_dir/everything-server" "$inputs/assigned-wirecmd-skill.md" ;;
            mcpc)
                sha256sum -- "$inputs/config" "$tools/memory-server" "$tools/everything-server"
                printf '%s  %s\n' "$mcpc_tree_hash" 'tools/mcpc-runtime (source-tree digest)'
                ;;
            native) sha256sum -- "$native_mcp_dir/memory-server" "$native_mcp_dir/everything-server" "$native_mcp_dir/memory-mcp" "$native_mcp_dir/everything-mcp" ;;
        esac
    } >"$parent/staged-inputs.sha256"
}

tail -n +2 "$run_root/plan.tsv" | while IFS=$'\t' read -r sequence id condition preparation repetition; do
    stage_arm "$sequence" "$id" "$condition" "$preparation" "$repetition"
done

cp -- "$task_source" "$run_root/frozen-task.txt"
printf '%s\n' 'comparative matrix staged; see plan.tsv and docs/notes/comparative-matrix-scaffold.md'
